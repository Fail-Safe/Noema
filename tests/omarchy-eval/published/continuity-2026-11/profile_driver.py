#!/usr/bin/env python3
"""Explicit fresh-replication entry point for the frozen 8k continuity profile.

Portable source, not byte-identical to the private tested adapters. Uses the
public independent campaign's unchanged preflight/smoke/run/analyze/restore
operator gates and qualification policy. No action occurs on import. Running
preflight performs the underlying real executable/model checks; smoke/run need
--confirm-live. Supply an operator-owned --config and fresh --run-id. New private
plans are generated by the existing campaign; historical evidence is not read.
"""
from __future__ import annotations

import importlib
from pathlib import Path
import sys


def main(argv=None):
    here = Path(__file__).resolve().parent
    harness = here.parents[1]
    sys.path.insert(0, str(harness))
    campaign = importlib.import_module("independent_campaign")
    base = campaign.base
    previous_hook = base.PREFETCH_HOOK
    previous_hashes = campaign.own_hashes
    previous_env = base.Run.runtime_env
    previous_run_corpus = campaign.run_corpus
    hook = here / "profile_hook.py"

    def own_hashes():
        result = previous_hashes()
        result.update({path.name: campaign.sha256_file(path) for path in (Path(__file__).resolve(), hook)})
        return result

    def runtime_env(run, case=None, *, capture=False):
        # Only the returned child environment changes; os.environ is untouched.
        env = previous_env(run, case, capture=capture)
        for key in tuple(env):
            if key.startswith(("NOEMA_", "TYPESAFE", "CLEF")):
                env.pop(key)
        return env

    def run_corpus(parent, parent_state, spec, phase):
        unit = campaign.CorpusRun(parent, spec)
        if not unit.exists():
            unit.save_state(campaign.fresh_unit_state(parent_state, unit))
        base.ensure_runtime(unit)
        config = unit.runtime_root / "xdg-config" / "noema" / "config.yaml"
        if not config.exists():
            campaign.write_json(config, {"decision": {"enabled": False}})
        return previous_run_corpus(parent, parent_state, spec, phase)

    base.PREFETCH_HOOK = hook
    campaign.own_hashes = own_hashes
    base.Run.runtime_env = runtime_env
    campaign.run_corpus = run_corpus
    try:
        return campaign.main(argv)
    finally:
        base.PREFETCH_HOOK = previous_hook
        campaign.own_hashes = previous_hashes
        base.Run.runtime_env = previous_env
        campaign.run_corpus = previous_run_corpus
        sys.path.remove(str(harness))


if __name__ == "__main__":
    raise SystemExit(main())
